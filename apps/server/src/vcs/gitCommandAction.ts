export type KnownGitCommandOperation = keyof typeof GIT_COMMAND_OPERATION_ACTIONS;

export const GIT_COMMAND_OPERATION_LIST = Object.keys(
  GIT_COMMAND_OPERATION_ACTIONS,
) as ReadonlyArray<KnownGitCommandOperation>;

const GIT_COMMAND_ACTION_LOOKUP: ReadonlyMap<string, GitCommandAction> = new Map(
  Object.entries(GIT_COMMAND_OPERATION_ACTIONS),
);

export function resolveGitCommandAction(operation: KnownGitCommandOperation): GitCommandAction {
  return GIT_COMMAND_OPERATION_ACTIONS[operation];
}

export function inferGitCommandAction(operation: string): GitCommandAction | undefined {
  return GIT_COMMAND_ACTION_LOOKUP.get(operation);
}
